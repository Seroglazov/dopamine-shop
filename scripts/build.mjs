import { cp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { validateCatalog } from '../src/js/commerce.js';
const data=JSON.parse(await readFile(new URL('../src/data/catalog.json',import.meta.url),'utf8'));
validateCatalog(data);
await mkdir('dist',{recursive:true});
await cp('src','dist',{recursive:true});
await mkdir('dist/vendor',{recursive:true});
for(const name of ['gsap.min.js','ScrollTrigger.min.js']) await cp(`node_modules/gsap/dist/${name}`,`dist/vendor/${name}`);
await writeFile('dist/robots.txt','User-agent: *\nAllow: /\n');
console.log(`Dopamine built: ${data.products.length} verified products. Static output: dist/`);
